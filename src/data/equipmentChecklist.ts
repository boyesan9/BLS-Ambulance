export function createFreshEquipmentChecklist(prefillMinimum = false): EquipmentCheckItem[] {
  return EQUIPMENT_TEMPLATE_ITEMS.map((item) => {
    const qty = prefillMinimum && item.minCount !== null ? item.minCount : 0;
    const isComplete = item.minCount === null ? true : qty >= item.minCount;
    return {
      ...item,
      availableQty: qty,
      conditionStatus: isComplete ? 'ready' : 'incomplete',
      notes: '',
    };
  });
}
